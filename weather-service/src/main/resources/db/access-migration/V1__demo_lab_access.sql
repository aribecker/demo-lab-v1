CREATE TABLE demo_lab.users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 first_name VARCHAR(80) NOT NULL,
 last_name VARCHAR(80) NOT NULL,
 email VARCHAR(254) UNIQUE,
 principal_kind VARCHAR(16) NOT NULL CHECK (principal_kind IN ('USER','EVERYONE')),
 system_key VARCHAR(20) UNIQUE,
 CHECK ((principal_kind='USER' AND email IS NOT NULL AND email=LOWER(email)) OR (principal_kind='EVERYONE' AND email IS NULL AND system_key='everyone'))
);
CREATE TABLE demo_lab.groups (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE);
CREATE TABLE demo_lab.group_permissions (
 group_id BIGINT NOT NULL REFERENCES demo_lab.groups(id) ON DELETE CASCADE,
 permission VARCHAR(16) NOT NULL CHECK (permission IN ('SIMULATOR','USERS','GROUPS')),
 PRIMARY KEY (group_id,permission)
);
CREATE TABLE demo_lab.memberships (
 group_id BIGINT NOT NULL REFERENCES demo_lab.groups(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES demo_lab.users(id) ON DELETE CASCADE,
 PRIMARY KEY (group_id,user_id)
);
CREATE TABLE demo_lab.bootstrap_state (id INTEGER PRIMARY KEY CHECK (id=1), initialized BOOLEAN NOT NULL);
